"""Generate the reason code section of README.md from ``rmig/reasons.py``.

Usage::

    python3 scripts/gen_reason_codes_doc.py [--readme <README.md>] [--check]

The section sits between ``<!-- reason-codes:begin -->`` and ``<!-- reason-codes:end -->``. It has one heading per
code, equal to the code, so the lower-case anchor that ``report.md`` links to (``README.md#rm-r-frequency``)
exists. Under each heading: the state the code causes, whether it propagates from a parent rule to its children,
the fidelity it implies on an ``AUTO`` item, and the fixed text.

``--check`` writes nothing: it exits 1 when the section differs from what the catalog generates. Deterministic; no
network access.
"""

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOL = os.path.dirname(HERE)
sys.path.insert(0, TOOL)

from rmig import reasons as R  # noqa: E402

DEFAULT_README = os.path.join(TOOL, "README.md")
BEGIN = "<!-- reason-codes:begin -->"
END = "<!-- reason-codes:end -->"

SCOPES = [
    ("R", "Rules"),
    ("F", "Fields"),
    ("S", "Stock content"),
    ("D", "Decoders"),
    ("L", "Lists"),
    ("P", "Policy and spaces"),
    ("X", "General"),
]


def md_text(text):
    """The catalog text as Markdown: ``<element>`` names in code format."""
    return re.sub(r"(<[^<>]+>(?:<[^<>]+>)*)", r"`\1`", text)


def render():
    codes = list(R.CATALOG.values())
    out = []
    w = out.append
    w(BEGIN)
    w("<!-- Generated by scripts/gen_reason_codes_doc.py from rmig/reasons.py: do not edit by hand. -->")
    w("")
    w("A code reads `RM-<scope>-<name>`. **State** is the state the code gives the item (the item takes the highest")
    w("of its codes). **Propagates** `yes`: a child rule of an item with this code gets it too. **Fidelity**")
    w("`approximate`: an `AUTO` item with this code is equivalent except for the named difference.")
    for key, title in SCOPES:
        group = [c for c in codes if c.code.split("-")[1] == key]
        if not group:
            continue
        w("")
        w("### %s" % title)
        for c in group:
            fid = c.fidelity or ("exact" if c.state == R.AUTO else "-")
            w("")
            w("#### %s" % c.code)
            w("")
            w("State `%s` · propagates %s · fidelity %s. %s" % (
                c.state, "yes" if c.propagates else "no", fid, md_text(c.text)))
    w("")
    w(END)
    return "\n".join(out)


def splice(readme_text, section):
    start = readme_text.index(BEGIN)
    end = readme_text.index(END, start) + len(END)
    return readme_text[:start] + section + readme_text[end:]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--readme", default=DEFAULT_README, help="the README to update (default: the tool's README.md)")
    ap.add_argument("--check", action="store_true", help="exit 1 if the section differs from the catalog")
    args = ap.parse_args(argv)
    path = os.path.normpath(args.readme)
    with open(path, "r", encoding="utf-8") as fh:
        current = fh.read()
    if BEGIN not in current or END not in current:
        print("%s has no %s ... %s markers" % (path, BEGIN, END), file=sys.stderr)
        return 2
    new = splice(current, render())
    if args.check:
        if new != current:
            print("%s is out of date: run scripts/gen_reason_codes_doc.py" % path, file=sys.stderr)
            return 1
        return 0
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(new)
    print("wrote %s (%d codes)" % (path, len(R.CATALOG)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
